#!/usr/bin/env python3
"""Collect the <style> blocks from the store's custom Shopify sections
(export/theme) into assets/ballers.css, so the static site looks the same.

Usage: python3 tools/extract_css.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THEME = os.path.join(ROOT, "export/theme")

# Order matters: later files may override earlier ones, same as on Shopify.
SOURCES = [
    "snippets/ballers-header-css-main.liquid",
    "snippets/ballers-header-css-drawer.liquid",
    "snippets/ballers-header-css-responsive.liquid",
    "sections/ballers-custom-header.liquid",
    "sections/home-featured-demo-products.liquid",
    "snippets/ballers-home-categories.liquid",
    "snippets/ballers-home-faq.liquid",
    "snippets/ballers-home-css-products.liquid",
    "snippets/ballers-home-css-categories.liquid",
    "snippets/ballers-home-css-gallery.liquid",
    "snippets/ballers-home-css-responsive.liquid",
    "sections/ballers-retro-collection.liquid",
    "sections/ballers-product-main.liquid",
    "sections/ballers-cart-page.liquid",
    "sections/ballers-search-results.liquid",
]


def main():
    parts = ["/* Generated by tools/extract_css.py from export/theme - do not edit by hand. */"]
    for rel in SOURCES:
        with open(os.path.join(THEME, rel), encoding="utf-8") as f:
            src = f.read()
        for block in re.findall(r"<style[^>]*>(.*?)</style>", src, re.S):
            # Theme asset references become a CSS variable set from assets/config.js.
            block = re.sub(r"url\('\{\{\s*\"([^\"]+)\"\s*\|\s*asset_url\s*\}\}'\)", r"var(--asset-\1)", block)
            block = block.replace("var(--asset-world.png)", "var(--asset-world)")
            leftover = re.findall(r"\{\{.*?\}\}|\{%.*?%\}", block)
            if leftover:
                raise SystemExit(f"Liquid left in {rel}: {leftover[:3]}")
            parts.append(f"\n/* ---- {rel} ---- */\n{block.strip()}\n")
    out = os.path.join(ROOT, "assets/ballers.css")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(parts))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
